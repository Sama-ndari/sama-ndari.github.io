function safeStorage(key, value) {
  try {
    if (value === undefined) return localStorage.getItem(key);
    localStorage.setItem(key, value);
  } catch (_) {
    return null;
  }
}

let _lang = "en";

function getLang() {
  return safeStorage("sama-lang") || _lang;
}

function setLang(lang) {
  _lang = lang;
  safeStorage("sama-lang", lang);
}

function t(key) {
  const lang = getLang();
  return I18N[lang]?.[key] || I18N.en[key] || key;
}

function applyI18nHead() {
  if (typeof document === "undefined") return;
  const lang = getLang();
  document.documentElement.setAttribute("lang", lang === "fr" ? "fr" : "en");
}

try {
  if (typeof window !== "undefined") window.applyI18nHead = applyI18nHead;
} catch (_e) {}

/* --------------------------------------------------------------------------
   Color theme (light / dark). Applied before paint to avoid a flash.
   -------------------------------------------------------------------------- */
function getTheme() {
  const stored = safeStorage("sama-theme");
  if (stored === "light" || stored === "dark") return stored;
  try {
    if (window.matchMedia && window.matchMedia("(prefers-color-scheme: light)").matches) {
      return "light";
    }
  } catch (_e) {
    /* matchMedia unavailable */
  }
  return "dark";
}

function setTheme(theme) {
  const value = theme === "light" ? "light" : "dark";
  safeStorage("sama-theme", value);
  applyThemeHead();
}

function applyThemeHead() {
  if (typeof document === "undefined") return;
  document.documentElement.setAttribute("data-theme", getTheme());
}

try {
  if (typeof window !== "undefined") {
    window.getTheme = getTheme;
    window.setTheme = setTheme;
    window.applyThemeHead = applyThemeHead;
  }
  applyThemeHead();
} catch (_e) {}

function applyI18n() {
  applyI18nHead();

  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    const key = el.getAttribute("data-i18n");
    const val = t(key);
    if (!val || val === key) return;
    el.innerHTML = val;
  });

  document.querySelectorAll("[data-i18n-text]").forEach(function (el) {
    const key = el.getAttribute("data-i18n-text");
    const val = t(key);
    if (!val) return;
    el.textContent = val;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    const key = el.getAttribute("data-i18n-placeholder");
    el.placeholder = t(key);
  });

  document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
    const key = el.getAttribute("data-i18n-title");
    el.title = t(key);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach(function (el) {
    const key = el.getAttribute("data-i18n-aria-label");
    const val = t(key);
    if (!val) return;
    el.setAttribute("aria-label", val);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
    const key = el.getAttribute("data-i18n-alt");
    const val = t(key);
    if (!val) return;
    el.setAttribute("alt", val);
  });

  if (document.body.classList.contains("page-ai-clone")) {
    document.title = t("page_title_ai");
    const desc = document.querySelector('meta[name="description"]');
    if (desc) {
      desc.setAttribute("content", t("meta_desc_ai"));
    }
  }

}
